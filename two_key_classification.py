def get_category(char):
    """Look up category of a character. Returns (letter, category) or None."""
    for letter, cats in two_key_classification.items():
        for category, chars in cats.items():
            if char in chars:
                return letter, category
    return None

def chars_by_category(letter):
    """Return dict of category -> list of characters for a given letter."""
    cats = two_key_classification.get(letter.upper(), {})
    return {k: list(v) for k, v in cats.items() if v}
